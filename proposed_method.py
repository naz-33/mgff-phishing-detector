def get_wordnet_pos(nltk_tag):
    if nltk_tag.startswith('V'):
        return 'v'
    return 'n'


def clean_for_stylometrics(text):
    text = str(text)
    text = re.sub(r'<[^>]+>', ' ', text)   # Step 1: HTML tag removal
    text = re.sub(r'\s+', ' ', text)
    return text.strip()

def full_preprocess(text):
    """Table 3 Steps 1-10, run on top of the lightly-cleaned text, for the
    TF-IDF branches only."""
    text = str(text)

    text = re.sub(r'<[^>]+>', ' ', text)                     # Step 1: HTML removal
    text = re.sub(r'https?://\S+|www\.\S+', ' ', text)       # Step 2: URL removal
    text = re.sub(r'\S+@\S+', ' ', text)                     # Step 3: Email removal
    # Step 4 (Raw Corpus Preservation) = clean_for_stylometrics(), done separately
    text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)               # Step 5: Special char removal
    text = re.sub(r'\s+', ' ', text).strip()                  # Step 6: Whitespace normalization
    text = text.lower()                                       # Step 7: Lowercasing

    tokens = word_tokenize(text)                              # Step 8: Tokenization
    tokens = [t for t in tokens if t not in STOPWORDS]         # Step 9: Stop word removal

    tagged = nltk.pos_tag(tokens)                              # Step 10: Lemmatization
    tokens = [
        LEMMATIZER.lemmatize(tok, get_wordnet_pos(tag))
        for tok, tag in tagged
    ]

    return ' '.join(tokens)

