def standardize_dataset(dataframe, text_column, label_column, source_name, label_mapper):
    """Standardize dataset with consistent column names and labels."""
    # Select relevant columns
    df = dataframe[[text_column, label_column]].dropna().copy()

    # Rename text column to 'email_text'
    df.rename(columns={text_column: 'email_text'}, inplace=True)

    # Apply label mapping
    df['label'] = df[label_column].apply(label_mapper)

    # Add source identifier
    df['source'] = source_name

    # Drop rows where label mapping failed (returned None or NaN)
    df = df.dropna(subset=['label'])

    # Ensure label is integer
    df['label'] = df['label'].astype(int)

    return df[['email_text', 'label', 'source']]

