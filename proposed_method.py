def calculate_ece(y_true, y_prob, n_bins=10):
    '''Calculates the Expected Calibration Error (ECE).'''
    bins = np.linspace(0.1, 1.0, n_bins)
    bin_low = np.insert(bins, 0, 0.0)
    bin_high = np.append(bins, 1.0)

    ece = 0
    total_samples = len(y_true)

    for i in range(n_bins):
        # Get samples in the current bin
        bin_indices = np.where(
            (y_prob > bin_low[i]) & (y_prob <= bin_high[i])
        )
        bin_y_true = y_true[bin_indices]
        bin_y_prob = y_prob[bin_indices]

        if len(bin_y_true) > 0:
            accuracy = np.mean(bin_y_true)
            confidence = np.mean(bin_y_prob)
            ece += (len(bin_y_true) / total_samples) * np.abs(accuracy - confidence)
    return ece


